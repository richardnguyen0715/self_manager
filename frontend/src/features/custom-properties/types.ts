// ─── Custom properties (per-project fields on work items) ─────────────────────

export const PROPERTY_TYPES = [
  "text",
  "number",
  "select",
  "multi_select",
  "date",
  "checkbox",
  "url",
] as const;

export type PropertyType = (typeof PROPERTY_TYPES)[number];

export const PROPERTY_TYPE_LABELS: Record<PropertyType, string> = {
  text: "Text",
  number: "Number",
  select: "Select",
  multi_select: "Multi-select",
  date: "Date",
  checkbox: "Checkbox",
  url: "URL",
};

/** Types whose value is picked from the property's `options`. */
export function isOptionType(type: PropertyType): boolean {
  return type === "select" || type === "multi_select";
}

export interface PropertyOption {
  /** Short string id, generated by the server when absent on create. */
  id: string;
  label: string;
  color: string | null;
}

/** Row returned by GET /api/custom-properties. */
export interface CustomProperty {
  id: string;
  project_id: string;
  name: string;
  type: PropertyType;
  options: PropertyOption[];
  position: number;
  created_at: string;
  updated_at: string;
}

/**
 * Stored value. Shape depends on the property type:
 * text/url/date/select(option id) → string, number → number,
 * checkbox → boolean, multi_select → string[]. `null` means no value.
 */
export type PropertyValue = string | number | boolean | string[] | null;

/** Element of GET /api/custom-properties/work-items/:work_item_id. */
export interface WorkItemPropertyValue {
  property_id: string;
  value: PropertyValue;
}

/** Element of GET /api/custom-properties/values?project_id=. */
export interface ProjectPropertyValue {
  work_item_id: string;
  property_id: string;
  value: PropertyValue;
}

/** Option as sent on create/update. `id` is omitted for new options. */
export interface PropertyOptionInput {
  id?: string;
  label: string;
  color?: string | null;
}

export interface CreateCustomPropertyPayload {
  project_id: string;
  name: string;
  type: PropertyType;
  options?: PropertyOptionInput[];
}

export interface UpdateCustomPropertyPayload {
  name?: string;
  options?: PropertyOptionInput[];
  position?: number;
}

export interface SetPropertyValuePayload {
  value: PropertyValue;
}

/** Limits mirrored from the backend validation. */
export const PROPERTY_NAME_MAX = 60;
export const PROPERTY_OPTION_LABEL_MAX = 60;
export const PROPERTY_TEXT_MAX = 2000;

